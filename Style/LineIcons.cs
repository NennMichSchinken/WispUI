using System;
using System.Collections.Generic;
using System.Globalization;
using System.Numerics;
using Dalamud.Bindings.ImGui;

namespace WispUI.Style;

/// <summary>
/// One icon as the drawing needs it: a few outlines on a 24 by 24 grid, already flattened to
/// points.
/// <para>
/// Built once from the shape data and kept. The draw path walks points and nothing else — no
/// parsing, no curve maths, no allocation.
/// </para>
/// </summary>
internal sealed class LineIcon
{
    public LineIcon(Vector2[][] outlines, bool[] closed, Vector3[] circles)
    {
        this.Outlines = outlines;
        this.Closed = closed;
        this.Circles = circles;
    }

    /// <summary>Each stroke of the icon, as points on the 24 grid.</summary>
    public Vector2[][] Outlines { get; }

    /// <summary>Whether each outline joins back to its start.</summary>
    public bool[] Closed { get; }

    /// <summary>Circles the icon draws, as centre and radius on the same grid.</summary>
    public Vector3[] Circles { get; }
}

/// <summary>
/// WispUI's line icons, drawn from vector outlines rather than from a font or a picture.
/// <para>
/// 🔴 The shapes come from <b>Lucide</b> (lucide.dev), ISC licence, copyright Lucide Icons and
/// Contributors — the same set LumenUI uses, which is why they are here: one look across both
/// projects, and a set we control rather than whatever an icon font happens to ship. The
/// licence text is kept beside them in <c>Icons/LUCIDE-LICENSE.txt</c> and must stay with any
/// copy of this plugin. Each entry below names the file it was taken from, unchanged.
/// </para>
/// <para>
/// 🔴 Why vectors and not a font: Lucide publishes no font file — theirs is generated by a
/// build we do not run — and the alternative that was tried first, the icon face Dalamud
/// bundles, drew empty boxes (Florian, 2026-09-19). Drawing the outlines has the better
/// properties anyway: sharp at any size, our own colour, and a new icon is one string.
/// </para>
/// <para>
/// Lucide draws on a 24 by 24 grid with a 2 wide stroke, round caps and round joins. Those
/// are the numbers below, and keeping them is what makes a WispUI icon look like a Lucide
/// icon rather than like a traced one.
/// </para>
/// </summary>
internal static class LineIcons
{
    /// <summary>The grid every outline is stated on.</summary>
    public const float Grid = 24f;

    /// <summary>Lucide's own stroke width, on that grid.</summary>
    public const float Stroke = 2f;

    // --- the set, each taken from the file named beside it --------------------

    /// <summary>eye.svg</summary>
    public static LineIcon Eye => Get(
